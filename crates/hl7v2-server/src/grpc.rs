fn grpc_message_bytes(
    message: &[u8],
    mllp_framed: bool,
    max_message_size: usize,
) -> Result<&[u8], crate::handlers::RequestError> {
    crate::handlers::enforce_decoded_message_size(message, mllp_framed, max_message_size)
}

fn grpc_status_from_request_error(error: crate::handlers::RequestError) -> Status {
    match error {
        crate::handlers::RequestError::App(crate::handlers::AppError::Parse(message)) => {
            let detail = message
                .strip_prefix("MLLP parse error: ")
                .unwrap_or(message.as_str());
            Status::invalid_argument(format!("Failed to unwrap MLLP: {detail}"))
        }
        error => Status::invalid_argument(error.to_string()),
    }
}

fn enforce_grpc_profile_fixture_sizes(
    fixtures: &[ProfileTestFixture],
    max_message_size: usize,
) -> Result<(), crate::handlers::RequestError> {
    for fixture in fixtures {
        crate::handlers::enforce_decoded_message_size_if_valid_mllp(
            &fixture.message,
            fixture.mllp_framed,
            max_message_size,
        )?;
    }

    Ok(())
}

fn enforce_grpc_corpus_message_sizes(
    messages: &[CorpusMessageInput],
    max_message_size: usize,
) -> Result<(), crate::handlers::RequestError> {
    for message in messages {
        let raw_bytes = message.message.as_slice();
        let mllp_framed = hl7v2::is_mllp_framed(raw_bytes);
        crate::handlers::enforce_decoded_message_size_if_valid_mllp(
            raw_bytes,
            mllp_framed,
            max_message_size,
        )?;
    }

    Ok(())
}

fn parse_grpc_message_response(
    message: &[u8],
    mllp_framed: bool,
    max_message_size: usize,
) -> ParseResponse {
    let message_bytes =
        match crate::handlers::enforce_decoded_message_size(message, mllp_framed, max_message_size)
        {
            Ok(message_bytes) => message_bytes,
            Err(error) => {
                let code = if matches!(error, crate::handlers::RequestError::MessageTooLarge { .. })
                {
                    "MESSAGE_TOO_LARGE"
                } else {
                    "MLLP_ERROR"
                };
                return ParseResponse {
                    success: false,
                    message: None,
                    errors: vec![Error {
                        code: code.to_string(),
                        message: error.to_string(),
                        details: std::collections::HashMap::new(),
                        trace_id: String::new(),
                    }],
                    metadata: None,
                };
            }
        };

    let parse_result = rust_parse(message_bytes);

    match parse_result {
        Ok(msg) => {
            let metadata = extract_grpc_metadata(&msg);
            let proto_msg = proto::Message::from(msg);

            ParseResponse {
                success: true,
                message: Some(proto_msg),
                errors: Vec::new(),
                metadata: Some(metadata),
            }
        }
        Err(e) => ParseResponse {
            success: false,
            message: None,
            errors: vec![Error {
                code: "PARSE_ERROR".to_string(),
                message: format!("Failed to parse HL7: {}", e),
                details: std::collections::HashMap::new(),
                trace_id: String::new(),
            }],
            metadata: None,
        },
    }
}

fn parse_stream_response_from_parse_response(response: ParseResponse) -> ParseStreamResponse {
    ParseStreamResponse {
        success: response.success,
        message: response.message,
        errors: response.errors,
        metadata: response.metadata,
    }
}

fn grpc_requested_schema_version(version: i32, artifact: &str) -> Result<i32, String> {
    match version {
        0 | 1 => Ok(1),
        2 => Ok(2),
        other => Err(format!(
            "unsupported {artifact} schema version {other}; expected 1 or 2"
        )),
    }
}

fn compute_sha256(input: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(input.as_bytes());
    format!("{:x}", hasher.finalize())
}

fn proto_location_from_issue_path(path: &str) -> Location {
    if let Ok(located) = hl7v2::parse_located_path(path) {
        let repetition = located
            .path
            .repetition
            .or(located.segment_repetition)
            .map(usize_to_i32)
            .unwrap_or_default();

        return Location {
            segment: located.path.segment,
            field: usize_to_i32(located.path.field),
            component: located.path.component.map(usize_to_i32).unwrap_or_default(),
            repetition,
            byte_offset: 0,
        };
    }

    if let Some(location) = proto_segment_occurrence_location_from_issue_path(path) {
        return location;
    }

    proto_location_from_legacy_issue_path(path)
}

fn proto_segment_occurrence_location_from_issue_path(path: &str) -> Option<Location> {
    let path = path.trim();
    if path.is_empty() || path.contains('.') || path.contains('-') {
        return None;
    }

    let has_repetition_selector = path.contains('[');
    let (segment, repetition) = if has_repetition_selector {
        let without_closing_bracket = path.strip_suffix(']')?;
        let (segment, repetition) = without_closing_bracket.split_once('[')?;
        let repetition = repetition.parse::<usize>().ok()?;
        (segment, repetition)
    } else {
        (path, 0)
    };

    if segment.is_empty()
        || (has_repetition_selector && repetition == 0)
        || !segment.chars().all(|ch| ch.is_ascii_alphanumeric())
    {
        return None;
    }

    Some(Location {
        segment: segment.to_ascii_uppercase(),
        field: 0,
        component: 0,
        repetition: usize_to_i32(repetition),
        byte_offset: 0,
    })
}

fn proto_location_from_legacy_issue_path(path: &str) -> Location {
    let mut loc = Location::default();
    let parts: Vec<&str> = path.split('.').collect();
    if !parts.is_empty() {
        loc.segment = parts[0].to_string();
    }
    if parts.len() > 1 {
        loc.field = parts[1].parse().unwrap_or(0);
    }
    if parts.len() > 2 {
        loc.component = parts[2].parse().unwrap_or(0);
    }
    loc
}

struct GrpcRedactedQuarantineContext<'a> {
    state: &'a AppState,
    raw_input: &'a [u8],
    profile_yaml: &'a str,
    policy_text: &'a str,
    redacted_message: &'a hl7v2::Message,
    redacted_hl7: &'a str,
    redaction_receipt: &'a ServerRedactionReceipt,
    validation_report: &'a hl7v2::ValidationReport,
}

enum GrpcQuarantineOutputError {
    MissingRoot,
    Write(crate::evidence::EvidenceBundleError),
}

fn maybe_write_grpc_redacted_quarantine(
    context: GrpcRedactedQuarantineContext<'_>,
) -> Result<Option<ServerQuarantineOutputSummary>, GrpcQuarantineOutputError> {
    let GrpcRedactedQuarantineContext {
        state,
        raw_input,
        profile_yaml,
        policy_text,
        redacted_message,
        redacted_hl7,
        redaction_receipt,
        validation_report,
    } = context;

    if validation_report.valid || !state.quarantine.enabled {
        return Ok(None);
    }

    let root = state
        .quarantine
        .path
        .as_deref()
        .ok_or(GrpcQuarantineOutputError::MissingRoot)?;
    let output_id = generated_quarantine_id();
    let summary =
        crate::evidence::write_quarantine_output(crate::evidence::QuarantineOutputWriteRequest {
            root,
            output_id: &output_id,
            config: &state.quarantine,
            raw_input,
            profile_yaml,
            policy_text,
            redacted_message,
            redacted_hl7,
            redaction_receipt,
            validation_report,
        })
        .map_err(GrpcQuarantineOutputError::Write)?;

    Ok(Some(summary))
}

fn generated_quarantine_id() -> String {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |duration| duration.as_nanos());
    format!("quarantine-{}-{nanos}", std::process::id())
}

fn validated_grpc_corpus_message_ids(
    messages: &[CorpusMessageInput],
) -> Result<Vec<String>, &'static str> {
    if messages.is_empty() {
        return Err("messages must contain at least one message");
    }

    messages
        .iter()
        .enumerate()
        .map(|(index, message)| {
            let label = message
                .id
                .clone()
                .unwrap_or_else(|| format!("message-{}", index.saturating_add(1)));
            validate_grpc_corpus_message_id(&label)?;
            Ok(label)
        })
        .collect()
}

fn validate_grpc_corpus_message_id(label: &str) -> Result<(), &'static str> {
    if label.is_empty() || label == "." || label == ".." || label.len() > 128 {
        return Err("corpus message id must be 1-128 characters and cannot be '.' or '..'");
    }

    if !label
        .chars()
        .all(|character| character.is_ascii_alphanumeric() || matches!(character, '.' | '_' | '-'))
    {
        return Err("corpus message id must use only ASCII letters, numbers, '.', '_' or '-'");
    }

    Ok(())
}

